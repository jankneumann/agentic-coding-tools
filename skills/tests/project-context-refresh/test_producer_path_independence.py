"""A producer's report is identical for relative and absolute repository paths.

ri-10 task 6.1, design D12.

``tree_diff`` carries an unstated precondition: **a renderer's output must not
depend on its input paths.** A renderer that interpolates the paths it was handed
into its output produces a tempdir render that can never byte-match the committed
tree, and the producer reports that as *staleness* — a diagnosis that sends the
reader looking for a stale artifact instead of a broken renderer. That is exactly
how ``decisions.timeline`` came to report 17 stale files on a tree whose
``docs/decisions/`` was provably fresh.

The guard is written over ``registry.list_producers()`` rather than over the one
producer that failed it, because the precondition belongs to every tempdir-diff
producer, current and future, and one enumerating test is cheaper than auditing
each renderer. ``TestTheAssertionCanFail`` registers a deliberately
path-dependent producer and requires the assertion to catch and name it, so a
vacuous version of this module fails its own suite.
"""

from __future__ import annotations

import subprocess
import tempfile
from pathlib import Path
from typing import Any

import pytest

import results as R
from _runtime import ProducerStatus, Remediation
from registry import Producer, ProducerSpec, list_producers, register, run_producer
from tree_diff import diff_trees

_CAPABILITY = "software-factory-tooling"


# --------------------------------------------------------------------------- #
# The assertion
# --------------------------------------------------------------------------- #
def report_for(repository: Path, revision: str) -> dict[str, dict[str, Any]]:
    """Run every registered producer in check mode; return report dicts by id.

    ``ProducerResult.to_dict`` is fully content-derived — it carries no clock, no
    duration, and no path outside the repository — so equality between two dicts
    is equality of the whole report.
    """
    specs = list_producers()
    assert specs, "the registry exposed no producers; the assertion would be vacuous"
    return {
        spec.producer_id: run_producer(spec.producer_id, "check", repository, revision).to_dict()
        for spec in specs
    }


def _artifact_summary(report: dict[str, Any]) -> list[str]:
    """``path change sha256[:12]`` per artifact — the digest is what usually differs."""
    return [
        f"{a['path']} {a['change']} {(a['sha256'] or 'none')[:12]}"
        for a in report["artifacts"]
    ]


def assert_reports_are_path_independent(
    repository_root: Path, revision: str
) -> dict[str, dict[str, Any]]:
    """Assert each producer reports identically for a relative and absolute path.

    *repository_root* must be a path relative to the current working directory.
    Raises ``AssertionError`` naming the offending producer, so a failure points
    at a renderer rather than at a diff.
    """
    assert not repository_root.is_absolute(), (
        "pass a relative repository path; comparing two absolute spellings would "
        "not exercise the precondition"
    )
    relative_reports = report_for(repository_root, revision)
    absolute_reports = report_for(repository_root.resolve(), revision)

    assert sorted(relative_reports) == sorted(absolute_reports)
    for producer_id, relative in relative_reports.items():
        absolute = absolute_reports[producer_id]
        if relative == absolute:
            continue
        relative_artifacts = _artifact_summary(relative)
        absolute_artifacts = _artifact_summary(absolute)
        raise AssertionError(
            f"producer {producer_id!r} reported differently for a relative and an "
            "absolute repository path, so its renderer's output depends on its "
            "input paths — that is a producer defect, not staleness.\n"
            f"  relative: status={relative['status']} artifacts={relative_artifacts}\n"
            f"  absolute: status={absolute['status']} artifacts={absolute_artifacts}"
        )
    return relative_reports


# --------------------------------------------------------------------------- #
# Fixture: a committed checkout carrying every producer's inputs
# --------------------------------------------------------------------------- #
def _git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _managed(title: str, block_id: str, body: str) -> str:
    """A marker-managed inventory file, matching ``inventory_file._skeleton``."""
    return (
        f"# {title}\n\n"
        "<!-- This file is generated by a project-context producer. Edit prose "
        "outside the generated markers only; content inside the markers is "
        "overwritten on regeneration. -->\n\n"
        f"<!-- GENERATED: begin {block_id} -->\n"
        f"{body}\n"
        f"<!-- GENERATED: end {block_id} -->\n"
    )


def _seed_decision_index(repo: Path) -> None:
    """Commit the decision index as the canonical owner renders it.

    Seeded through the owner from a *relative* archive root — the spelling
    ``make decisions`` uses — so ``check`` has a real committed tree to compare
    against and ``decisions.timeline`` reports ``fresh`` rather than trivially
    reporting every file as added.
    """
    import sys

    owner_scripts = (
        Path(__file__).resolve().parents[2] / "explore-feature" / "scripts"
    )
    if str(owner_scripts) not in sys.path:
        sys.path.insert(0, str(owner_scripts))
    from archive_index import emit_decisions_from_archive

    cwd = Path.cwd()
    try:
        import os

        os.chdir(repo)
        emit_decisions_from_archive(
            archive_root=Path("openspec") / "changes",
            output_dir=Path("docs") / "decisions",
            capabilities_root=Path("openspec") / "specs",
            strict=False,
        )
    finally:
        import os

        os.chdir(cwd)


@pytest.fixture
def checkout(tmp_path: Path) -> tuple[Path, Path, str]:
    """Return ``(parent_dir, relative_repo_path, head_sha)``.

    Every producer must find real inputs and a committed output to compare
    against: a producer that bails out early would make the comparison prove
    nothing. Two marker inventories are committed deliberately stale so those
    producers report drift, and the decision index is committed fresh so
    ``decisions.timeline`` exercises the byte comparison rather than the
    everything-is-new path.
    """
    repo = tmp_path / "checkout"
    repo.mkdir()
    subprocess.run(["git", "init", str(repo)], check=True, capture_output=True)
    for key, value in (("user.email", "t@example.com"), ("user.name", "T")):
        _git(repo, "config", key, value)

    # documentation.inventory
