# --------------------------------------------------------------------------- #
# Scenario: Path dependence is detected as a defect, not as staleness
# --------------------------------------------------------------------------- #
class TestEveryProducerIsPathIndependent:
    def test_the_fixture_gives_the_decisions_producer_real_work(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        """A committed index rendered by the owner is what makes the diff real."""
        parent, repo, head = checkout
        monkeypatch.chdir(parent)

        index = repo / "docs" / "decisions"
        rendered = sorted(p.name for p in index.glob("*.md"))
        assert f"{_CAPABILITY}.md" in rendered
        assert "README.md" in rendered

        result = run_producer("decisions.timeline", "check", repo, head)
        assert result.status is ProducerStatus.FRESH, (
            "the committed index does not match a relative render, so the "
            f"comparison below would not be exercised: {result.to_dict()}"
        )

    def test_every_registered_producer_reports_identically(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        parent, repo, head = checkout
        monkeypatch.chdir(parent)

        reports = assert_reports_are_path_independent(repo, head)

        assert sorted(reports) == [spec.producer_id for spec in list_producers()]
        assert all(
            report["status"] != ProducerStatus.FAILED.value for report in reports.values()
        ), reports

    def test_the_producers_compared_something(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        """Identical reports from producers that never ran is not evidence."""
        parent, repo, head = checkout
        monkeypatch.chdir(parent)

        reports = report_for(repo, head)

        assert any(report["validations"] for report in reports.values())
        # The two marker inventories were committed stale on purpose.
        assert any(
            report["status"] == ProducerStatus.DEGRADED.value for report in reports.values()
        ), reports

    def test_the_enumeration_is_the_registry_not_a_literal_list(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        parent, repo, head = checkout
        monkeypatch.chdir(parent)
        register(_PathIndependentProducer("zz.registered-later"))

        reports = assert_reports_are_path_independent(repo, head)

        assert "zz.registered-later" in reports
        assert set(reports) == {spec.producer_id for spec in list_producers()}


# --------------------------------------------------------------------------- #
# Mutation proof: the assertion must be able to fail
# --------------------------------------------------------------------------- #
class _TempdirDiffProducer(Producer):
    """A tempdir-diff producer whose render optionally embeds the repository path."""

    _PREFIX = "docs/fixture"

    def __init__(self, producer_id: str, *, path_dependent: bool) -> None:
        self.spec = ProducerSpec(
            producer_id=producer_id,
            producer_version="1",
            owner="mutation-fixture",
            inputs=(),
            outputs=(f"{self._PREFIX}/",),
        )
        self._path_dependent = path_dependent

    def run(self, mode, repository, source_revision):  # noqa: ANN001
        repository = Path(repository)
        committed = repository / self._PREFIX
        with tempfile.TemporaryDirectory() as tmp:
            rendered = Path(tmp)
            body = f"repository: {repository}\n" if self._path_dependent else "fixed\n"
            (rendered / "rendered.md").write_text(body, encoding="utf-8")
            artifacts = diff_trees(
                committed, rendered, path_prefix=self._PREFIX, patterns=("*.md",)
            )
        if artifacts:
            return R.drift(
                self.spec.producer_id,
                self.spec.producer_version,
                artifacts=artifacts,
                validations=[R.failed_validation("fixture", "fixture output is stale")],
                remediation=[Remediation(summary="fixture")],
            )
        return R.fresh(
            self.spec.producer_id,
            self.spec.producer_version,
            validations=[R.passed("fixture", "fixture output is current")],
        )


class _PathIndependentProducer(_TempdirDiffProducer):
    def __init__(self, producer_id: str) -> None:
        super().__init__(producer_id, path_dependent=False)


class TestTheAssertionCanFail:
    def test_a_path_dependent_renderer_is_caught_and_named(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        parent, repo, head = checkout
        monkeypatch.chdir(parent)
        register(_TempdirDiffProducer("zz.path-dependent", path_dependent=True))

        with pytest.raises(AssertionError) as excinfo:
            assert_reports_are_path_independent(repo, head)

        message = str(excinfo.value)
        assert "zz.path-dependent" in message
        assert "producer defect, not staleness" in message

    def test_a_path_independent_renderer_passes(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        """The fixture pair differs only in path dependence, so the mutation is the cause."""
        parent, repo, head = checkout
        monkeypatch.chdir(parent)
        register(_TempdirDiffProducer("zz.path-independent", path_dependent=False))

        reports = assert_reports_are_path_independent(repo, head)

        assert reports["zz.path-independent"]["status"] == ProducerStatus.DEGRADED.value

    def test_the_assertion_rejects_an_absolute_repository_argument(
        self, checkout: tuple[Path, Path, str], monkeypatch
    ) -> None:
        """Two absolute spellings would compare a path against itself."""
        parent, repo, head = checkout
        monkeypatch.chdir(parent)

        with pytest.raises(AssertionError, match="relative repository path"):
            assert_reports_are_path_independent((parent / repo).resolve(), head)
